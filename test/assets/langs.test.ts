/**
 * Locks in the project rule that i18n keys are static and every shipped locale
 * carries the same key set.
 *
 * `assets/langs/ko.json` is the SSOT: `.eslintrc.js` points
 * `i18n-json/identical-keys` at it, and `src/utils/i18n.ts` derives the `t()`
 * argument type from its shape. A key that exists in `ko` but not in `ja`
 * typechecks fine and then silently falls back to English in the middle of a
 * Japanese app — this test is the thing that catches it.
 *
 * It also covers the two things the eslint plugin cannot check:
 * `{{placeholder}}` parity, and the invariant that every plural entry has an
 * `other` form in every locale (the pluralizer registered for ko/ja/zh/id asks
 * for `other`, so a missing one renders the raw key).
 *
 * Legacy `en ko ja zh id` files are generated by
 * `scripts/convert-legacy-strings.ts`. Additional developed-country locales
 * are authored as sibling JSON with the same key set.
 */
type Json = {[key: string]: Json | string};

const LOCALES: Record<string, Json> = {
  en,
  ko,
  ja,
  zh,
  id,
  de,
  es,
  fr,
  it: itLang,
  nl,
  pt,
  vi,
};
const META: Record<string, Json> = {
  en: metaEn,
  ko: metaKo,
  ja: metaJa,
  zh: metaZh,
  id: metaId,
  de: metaDe,
  es: metaEs,
  fr: metaFr,
  it: metaIt,
  nl: metaNl,
  pt: metaPt,
  vi: metaVi,
};

const REFERENCE = 'ko';

const otherLocales = Object.keys(LOCALES).filter(
  (locale) => locale !== REFERENCE,
);

const flatten = (value: Json, prefix = ''): [string, string][] =>
  Object.entries(value).flatMap(([key, child]) => {
    const path = prefix ? `${prefix}.${key}` : key;

    return typeof child === 'string'
      ? ([[path, child]] as [string, string][])
      : flatten(child, path);
  });

const keysOf = (value: Json): string[] =>
  flatten(value)
    .map(([path]) => path)
    .sort();

const placeholdersOf = (message: string): string[] =>
  (message.match(/\{\{\s*[\w.]+\s*\}\}|%\{[\w.]+\}/g) ?? [])
    .map((token) => token.replace(/[%{}\s]/g, ''))
    .sort();

const referenceKeys = keysOf(LOCALES[REFERENCE]);

describe('i18n key parity', () => {
  it('has a non-trivial key set to compare', () => {
    expect(referenceKeys.length).toBeGreaterThan(200);
  });

  it.each(otherLocales)('%s.json has the same key set as ko.json', (locale) => {
    expect(keysOf(LOCALES[locale])).toEqual(referenceKeys);
  });

  it.each(Object.keys(LOCALES))('%s.json has no empty string', (locale) => {
    const empty = flatten(LOCALES[locale])
      .filter(([, message]) => message.trim() === '')
      .map(([path]) => path);

    expect(empty).toEqual([]);
  });

  it('has no hyphen in any key (custom-syntax-validator.ts)', () => {
    expect(referenceKeys.filter((key) => key.includes('-'))).toEqual([]);
  });

  it.each(otherLocales)(
    '%s.json uses the same {{placeholders}} as ko.json',
    (locale) => {
      const reference = new Map(flatten(LOCALES[REFERENCE]));
      const drift = flatten(LOCALES[locale])
        .filter(
          ([path, message]) =>
            placeholdersOf(message).join(',') !==
            placeholdersOf(reference.get(path) ?? '').join(','),
        )
        .map(([path]) => path);

      expect(drift).toEqual([]);
    },
  );
});

describe('plural entries', () => {
  // A plural entry is any object whose children are all strings and which has
  // an `other` form. Detect them from the reference file and require the same
  // shape everywhere.
  const pluralPaths = [
    ...new Set(
      referenceKeys
        .filter((key) => /\.(zero|one|other)$/.test(key))
        .map((key) => key.replace(/\.(zero|one|other)$/, '')),
    ),
  ];

  it('has at least one plural entry', () => {
    expect(pluralPaths.length).toBeGreaterThan(0);
  });

  it.each(Object.keys(LOCALES))('%s.json defines every `other`', (locale) => {
    const keys = new Set(keysOf(LOCALES[locale]));
    const missing = pluralPaths.filter((path) => !keys.has(`${path}.other`));

    expect(missing).toEqual([]);
  });
});

describe('critical ledger copy', () => {
  it('keeps invite acceptance and rejection semantically distinct', () => {
    expect(en.ledger.accept).toBe('Accept');
    expect(en.ledger.reject).toBe('Reject');
    expect(ko.ledger.accept).toBe('수락');
    expect(ko.ledger.reject).toBe('거절');
    expect(ja.ledger.accept).toBe('参加する');
    expect(ja.ledger.reject).toBe('辞退する');
    expect(zh.ledger.accept).toBe('接受');
    expect(zh.ledger.reject).toBe('拒绝');
    expect(id.ledger.accept).toBe('Terima');
    expect(id.ledger.reject).toBe('Tolak');
  });

  it('uses entry terminology for empty ledgers in every locale', () => {
    expect(en.ledgerItem.empty).toBe('No entries yet.');
    expect(ko.ledgerItem.empty).toContain('내역');
    expect(ja.ledgerItem.empty).toContain('記録');
    expect(zh.ledgerItem.empty).toContain('记录');
    expect(id.ledgerItem.empty).toContain('catatan');
  });

  it('uses the financial meaning of income in Japanese', () => {
    expect(ja.ledgerItem.income).toBe('収入');
  });

  it('keeps the signed-out intro to the shared-ledger value line', () => {
    expect(ko.intro.signInSupporting).toBe(
      '각자 기록해도 함께 정리돼요. 생활비부터 여행 경비까지 투명하게 나눠보세요.',
    );
    expect(en.intro.signInSupporting).toMatch(/together|shared|split/i);
    expect(ko.intro.signInSupporting).not.toContain('함께 쓰는');
  });
});

describe('store metadata (assets/langs/meta)', () => {
  // Not part of the app string set — these are native manifest fields fed to
  // Info.plist through `app.config.ts`'s `locales`, and `.eslintignore`
  // excludes them from `i18n-json/identical-keys`. They still have to agree
  // with each other or a locale silently loses a permission dialog.
  const metaReference = keysOf(META[REFERENCE]);

  it.each(otherLocales)('meta/%s.json has the same key set', (locale) => {
    expect(keysOf(META[locale])).toEqual(metaReference);
  });

  // The location prompt was configured only as a Korean Info.plist base
  // string, so every non-Korean device asked for location in Korean.
  it.each(Object.keys(META))(
    'meta/%s.json localizes every permission prompt the app can show',
    (locale) => {
      expect(Object.keys(META[locale].ios).sort()).toEqual(
        expect.arrayContaining([
          'NSCameraUsageDescription',
          'NSFaceIDUsageDescription',
          'NSLocationWhenInUseUsageDescription',
          'NSPhotoLibraryAddUsageDescription',
          'NSPhotoLibraryUsageDescription',
        ]),
      );
    },
  );

  it.each(Object.keys(META))('meta/%s.json has no empty value', (locale) => {
    const empty = flatten(META[locale])
      .filter(([, message]) => message.trim() === '')
      .map(([path]) => path);

    expect(empty).toEqual([]);
  });
});
