#!/bin/sh
# Run by `bun install` (package.json `prepare`). The single source of BooKoo's
# git hooks: edit the hook bodies here, then rerun `bun install`.
#
# Trust model. The checks run the checkout's own package scripts (`lint:all`
# runs ESLint and ts-node scripts that import project code), so a hook must not
# fire on code nobody chose to trust:
#   - the hooks are written whole into git's hooks directory; nothing points git
#     at a tracked directory and no hook executes a tracked hook file;
#   - running this script (i.e. `bun install`) trusts this worktree's current
#     state only — HEAD plus whatever an in-progress merge, squash merge,
#     cherry-pick, revert or rebase is bringing in — recorded in its own git dir;
#   - a hook runs only while that state is unchanged, and a commit that passed
#     pre-commit on it becomes the new trusted state;
#   - checking out, pulling, rebasing or starting a merge of anything else fails
#     closed until someone reviews it and runs `bun install` again.
# Content a developer brings in file by file (`git checkout other -- path`,
# `git apply`, `git stash pop`) is their own edit, like any other change in the
# working tree, and is theirs to review before committing.
git rev-parse --git-common-dir >/dev/null 2>&1 || exit 0

# Earlier revisions set `core.hooksPath=.husky`; undo exactly that.
if [ "$(git config --get core.hooksPath)" = ".husky" ]; then
  git config --unset core.hooksPath
fi

hooks_dir="$(git rev-parse --git-common-dir)/hooks"
mkdir -p "$hooks_dir"

# The trust check needs all three hooks; never install a partial set.
for hook in pre-commit commit-msg post-commit; do
  if [ -e "$hooks_dir/$hook" ] && ! grep -q 'bookoo-hook-dispatcher' "$hooks_dir/$hook"; then
    echo "install-git-hooks: $hooks_dir/$hook was installed by hand; BooKoo hooks not installed." >&2
    exit 0
  fi
done

# Shared by every hook and by the trust step below. Checkouts from before these
# hooks existed (no installer) ran none and keep running none.
prelude='[ -f "$(git rev-parse --show-toplevel)/scripts/install-git-hooks.sh" ] || exit 0
git_dir="$(git rev-parse --git-dir)"
bookoo_state() {
  printf "%s" "$(git rev-parse -q --verify HEAD)"
  for f in MERGE_HEAD CHERRY_PICK_HEAD REVERT_HEAD REBASE_HEAD; do
    [ -f "$git_dir/$f" ] && printf " %s:%s" "$f" "$(tr -d "\n" <"$git_dir/$f")"
  done
  # `merge --squash` keeps HEAD and writes no MERGE_HEAD, only this message.
  [ -f "$git_dir/SQUASH_MSG" ] && printf " SQUASH_MSG:%s" "$(git hash-object "$git_dir/SQUASH_MSG")"
  return 0
}
trusted="$(cat "$git_dir/bookoo-trusted-state" 2>/dev/null)"'

check_trust='if [ -z "$trusted" ] || [ "$trusted" != "$(bookoo_state)" ]; then
  echo "BooKoo hooks: this worktree changed since it was trusted (checkout, pull," >&2
  echo "rebase or merge). The checks run its own package scripts; review it, then" >&2
  echo "run bun install." >&2
  exit 1
fi'

write_hook() {
  printf '#!/bin/sh\n# bookoo-hook-dispatcher: generated by scripts/install-git-hooks.sh\n%s\n%s\n' \
    "$prelude" "$2" >"$hooks_dir/$1"
  chmod 755 "$hooks_dir/$1"
}

# The commit skill promises exactly these gates. `bun lint:all` covers ESLint,
# i18n lint and every verify:* script; `convex/_generated/` is tracked, so
# typecheck is green on a fresh clone. A passing pre-commit records the state it
# checked and the exact tree it validated; post-commit trusts the new commit
# (an amend included) only when that commit has that tree, so a stale record
# left by a failed commit-msg cannot vouch for a later `--no-verify` commit.
write_hook pre-commit "rm -f \"\$git_dir/bookoo-pending-trust\"
$check_trust
bun lint:all && bun typecheck &&
  printf '%s\n%s\n' \"\$(bookoo_state)\" \"\$(git write-tree)\" >\"\$git_dir/bookoo-pending-trust\""
write_hook commit-msg "$check_trust
bunx commitlint --edit \"\$1\""
write_hook post-commit 'pending_state="$(sed -n 1p "$git_dir/bookoo-pending-trust" 2>/dev/null)"
pending_tree="$(sed -n 2p "$git_dir/bookoo-pending-trust" 2>/dev/null)"
rm -f "$git_dir/bookoo-pending-trust"
if [ -n "$trusted" ] && [ "$pending_state" = "$trusted" ] &&
  [ -n "$pending_tree" ] && [ "$pending_tree" = "$(git rev-parse HEAD^{tree})" ]; then
  bookoo_state >"$git_dir/bookoo-trusted-state"
fi'

# Trust this worktree's current state (the act of running `bun install` here).
eval "$prelude"
rm -f "$git_dir/bookoo-trusted-head"
bookoo_state >"$git_dir/bookoo-trusted-state"
